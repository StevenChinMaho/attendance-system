<?php

return [

    /*
    |--------------------------------------------------------------------------
    | 備份過期監控
    |--------------------------------------------------------------------------
    |
    | 備份最常見的失敗方式不是當下報錯，而是某天默默停掉、直到真的需要
    | 還原時才被發現——那正好是最糟的時間點。備份容器每次成功都會往
    | backup_runs 寫一筆心跳，這裡設定「多久沒有心跳就在畫面上示警」。
    |
    | 用資料庫心跳而不是去讀備份目錄，是為了讓 app 容器完全不需要知道
    | 備份檔放在哪（BACKUP_PATH 會隨著換主機而改變），也不必為此多掛
    | 一個 bind mount。代價是它證明的是「備份程序有跑完」而不是「檔案
    | 現在還在」——後者由 backup.sh verify 在主機上檢查。
    |
    */

    // 預設關閉：本機開發環境沒有備份容器，開著只會每頁都跳警告。
    // 正式環境在 .env.production 裡打開（見 .env.production.example）。
    'monitor_enabled' => (bool) env('BACKUP_MONITOR_ENABLED', false),

    // 超過這個時數沒有成功備份就示警。預設 48 小時而不是 24——備份是
    // 每天一次，抓 24 小時的話只要稍微延遲就會誤報；48 小時代表
    // 「連續漏掉兩次」，那就確實有問題了。
    'warn_after_hours' => (int) env('BACKUP_WARN_AFTER_HOURS', 48),

    // 誰看得到警告。導師與學生看到也無從處理，所以綁在稽核權限上
    // ——那本來就是「系統維運」性質的權限。
    'warning_permission' => 'audit.view',

];
